const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const JSZip = require('jszip');
const html = fs.readFileSync(path.join(__dirname, '../frontend/public/prototype.html'), 'utf8');
for (const script of html.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)) new vm.Script(script[1]);
const start = html.indexOf('  function _impXmlUnescape(');
const end = html.indexOf('  function _impParaStyle(', start);
assert.ok(start >= 0 && end > start);
const context = vm.createContext({});
vm.runInContext(html.slice(start, end), context);
const state = context._impCheckboxState;
const para = context._impParaText;
const sym = (code) => `<w:p><w:r><w:sym w:font="Wingdings 2" w:char="${code}"/></w:r><w:r><w:t>正在测评</w:t></w:r></w:p>`;
assert.equal(state(para(sym('00A3')), '正在测评'), false);
assert.equal(state(para(sym('F0A3')), '正在测评'), false);
assert.equal(state(para(sym('0052')), '正在测评'), true);
assert.equal(state(para(sym('F052')), '正在测评'), true);
assert.equal(state('正在测评', '正在测评'), null);
assert.equal(state('☑3DES □DES', 'DES'), false);
assert.equal(state('☑是否一致：☑是 □否', '否'), false);
assert.equal(state('□未定级，本次密评依据GB/T', '未定级，本次密评依据'), false);
assert.equal(state('☑已定级备案，第三等级', '已定级备案，第'), true);
assert.equal(state('□全国 ☑全省（区、市）', '全国'), false);
assert.equal(state('□全国 ☑全省（区、市）', '全省（区、市）'), true);
const schemeYes = '有密码应用方案，且通过密评，通过时间';
const schemeNo = '有密码应用方案，但未通过密评';
assert.equal(state('☑' + schemeYes + '：2026年06月10日 □' + schemeNo + ' □无密码应用方案', schemeYes), true);
assert.equal(state('☑' + schemeYes + '：2026年06月10日 □' + schemeNo + ' □无密码应用方案', schemeNo), false);
assert.equal(state('□' + schemeYes + '： □' + schemeNo, schemeNo), false);
assert.equal(state('□' + schemeYes + '： ☑' + schemeNo, schemeYes), false);
assert.equal(state('□' + schemeYes + '： ☑' + schemeNo, schemeNo), true);
console.log('Checkbox unit tests and inline JavaScript syntax: passed');
(async () => {
  if (!process.argv[2]) return;
  const zip = await JSZip.loadAsync(fs.readFileSync(process.argv[2]));
  const xml = await zip.file('word/document.xml').async('string');
  const paragraphs = [...xml.matchAll(/<w:p\b[^>]*>[\s\S]*?<\/w:p>/g)].map(m => para(m[0]));
  const schemeText = paragraphs.filter(p => p.includes('密码应用方案') && /[□☑]/.test(p)).join('\n');
  assert.equal(state(schemeText, schemeYes), true);
  assert.equal(state(schemeText, schemeNo), false);
  console.log('Actual DOCX scheme options: passed=true, not-passed=false');
  for (const key of ['已测评', '正在测评', '未测评', '未定级', '全国', '全省（区、市）']) {
    const text = paragraphs.find(p => /[□☑]/.test(p) && p.includes(key));
    assert.ok(text, `Missing option ${key}`);
    const actual = state(text, key);
    assert.equal(typeof actual, 'boolean', key);
    console.log(`${key}: ${actual ? 'checked' : 'unchecked'} (actual DOCX)`);
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
